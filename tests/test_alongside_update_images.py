"""#113: a saved alongside image must not mask the selected release at update time."""
import json
import os
import shutil
import subprocess
from pathlib import Path
from types import SimpleNamespace

import pytest
import yaml

from wam import alongside, cli, release_pins

ROOT = Path(__file__).resolve().parents[1]
APPS = ("wizard-agent-service", "wizard-ux")
OLD = "ghcr.io/example/old@sha256:" + "a" * 64


def override_path(c, app):
    return c.runtipi_root / "user-config/wizardapps" / app / "docker-compose.yml"


def read_override(c, app):
    return yaml.safe_load(override_path(c, app).read_text().replace("!reset", ""))["services"][app]


