    (hh / "config.yaml").write_text("owner sentinel\n")
    st = {"mode": "alongside", "agent": {"id": "host-hermes", "name": "host Hermes", "external": True,
          "hermes_home": str(hh), "origin": "http://127.0.0.1:8642", "uid": os.getuid(), "gid": os.getgid()},
          "shell": {"port": 8796, "share_history": False, "share_sessions": False},
          "service": {"port": 8797, "active": True}, "images": {app: OLD for app in APPS}}
    alongside.save(home, st)
    monkeypatch.setattr(alongside, "docker_rootless", lambda: False)
    monkeypatch.setattr(alongside, "detect", lambda *a: {"found": True, "api_origin": st["agent"]["origin"]})
    monkeypatch.setattr(cli.time, "sleep", lambda *a: None)
    # These tests isolate release-image selection; network preflight has its own fail-closed tests.
    monkeypatch.setattr(cli, "network_step", lambda *a, **k: {"ok": True, "errors": []})
    calls = []

    class RT:
        def app(self, urn):
            return {"app": {"status": "running", "version": "fixture"}}
        def update(self, urn, perform_backup=True):
            app = urn.split(":")[0]
            calls.append((urn, read_override(c, app)["image"], perform_backup))
